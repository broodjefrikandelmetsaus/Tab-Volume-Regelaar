create table public.volume_remote_devices (
  device_id uuid primary key,
  device_secret_hash text not null,
  pairing_code_hash text unique,
  paired_at timestamptz,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz,
  status jsonb not null default '{}'::jsonb
);
create table public.volume_remote_controllers (
  controller_id uuid primary key default gen_random_uuid(),
  device_id uuid not null references public.volume_remote_devices(device_id) on delete cascade,
  controller_secret_hash text not null unique,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz,
  is_active boolean not null default true
);
create table public.volume_remote_commands (
  id bigint generated by default as identity primary key,
  device_id uuid not null references public.volume_remote_devices(device_id) on delete cascade,
  action text not null check (action in ('set', 'setBrightness', 'lock')),
  percent integer check (percent is null or percent between 0 and 100),
  created_at timestamptz not null default now(),
  delivered_at timestamptz
);
create table public.volume_remote_pair_attempts (
  id bigint generated by default as identity primary key,
  ip_hash text not null,
  attempted_at timestamptz not null default now()
);
create index volume_remote_commands_pending_idx on public.volume_remote_commands (device_id, id) where delivered_at is null;
create index volume_remote_pair_attempts_ip_time_idx on public.volume_remote_pair_attempts (ip_hash, attempted_at desc);
alter table public.volume_remote_devices enable row level security;
alter table public.volume_remote_controllers enable row level security;
alter table public.volume_remote_commands enable row level security;
alter table public.volume_remote_pair_attempts enable row level security;
revoke all on table public.volume_remote_devices from anon, authenticated;
revoke all on table public.volume_remote_controllers from anon, authenticated;
revoke all on table public.volume_remote_commands from anon, authenticated;
revoke all on table public.volume_remote_pair_attempts from anon, authenticated;
grant all privileges on table public.volume_remote_devices to service_role;
grant all privileges on table public.volume_remote_controllers to service_role;
grant all privileges on table public.volume_remote_commands to service_role;
grant all privileges on table public.volume_remote_pair_attempts to service_role;
grant usage, select on sequence public.volume_remote_pair_attempts_id_seq to service_role;
grant usage, select on sequence public.volume_remote_commands_id_seq to service_role;
